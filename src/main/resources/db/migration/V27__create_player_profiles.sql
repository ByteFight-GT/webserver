CREATE TABLE player_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP NOT NULL DEFAULT now(),
    player_id BIGINT NOT NULL UNIQUE REFERENCES players (id),
    description VARCHAR(512),
    major VARCHAR(256),
    school VARCHAR(150),
    graduation_year INTEGER,
    CONSTRAINT player_profiles_has_details CHECK (
        description IS NOT NULL
        OR major IS NOT NULL
        OR school IS NOT NULL
        OR graduation_year IS NOT NULL
    )
);

CREATE INDEX idx_player_profiles_major ON player_profiles (major);
CREATE INDEX idx_player_profiles_school ON player_profiles (school);
CREATE INDEX idx_player_profiles_graduation_year ON player_profiles (graduation_year);
